export function progress(p) {
  return p.clues.length + p.wins.length + p.mail.length + p.plot.length;
}
export function unlocked(p, id) {
  return progress(p) >= (HIDDEN.find((x) => x.id === id)?.need ?? 0);
}
export function nextGoal(p) {
  if (p.active) return `${GAME_INFO[p.active.type][1]} · 저장한 게임 이어 하기`;
  if (p.plot.length < 4) {
    const chapter = PLOT[p.plot.length],
      missing = chapter.need.filter((x) => !p.clues.includes(x));
    return missing.length
      ? `${chapter.title}: ${PLACES.find((x) => x.id === CLUES[missing[0]].place).name} · ${TIMES[CLUES[missing[0]].time]} 조사`
      : `${chapter.title}: 수첩에서 추리 완성`;
  }
  return "집의 문이 열렸어요. 새 의뢰와 동료의 흔적을 만나 보세요.";
}
